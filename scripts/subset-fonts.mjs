import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { extname, join, relative } from 'node:path';
import process from 'node:process';
import subsetFont from 'subset-font';
import { pageKeyFromPath } from '../src/lib/page-key.mjs';
import {
  codePointsFrom,
  FONT_WEIGHTS,
  LAYOUT_FEATURES,
  partitionExt,
  weightedText,
  withCoreBaseline,
} from './font-text.mjs';

// ADR-0012: subset Noto Sans TC per weight to the glyphs that weight renders.
// Each weight gets a `core` subset (home page) and `ext` subsets (glyphs only
// used on other pages), so the home page never downloads case-study glyphs.
// Every page gets an `ext-<page>` subset containing all of its non-core glyphs.
// Extension faces are emitted only into that page's head; the generated global
// stylesheet contains core faces only.

const root = process.cwd();
const distDirectory = join(root, 'dist');
const homeHtml = join(distDirectory, 'index.html');

const sourceFontPath = join(
  root,
  'fonts-src',
  'noto-sans-tc',
  'NotoSansTC-wght.ttf',
);
const generatedDirectory = join(root, 'public', '_fonts');
const generatedCss = join(root, 'src', 'styles', 'noto-sans-tc.generated.css');
const generatedPageCss = join(
  root,
  'src',
  'styles',
  'noto-sans-tc.pages.generated.json',
);

async function filesBelow(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const path = join(directory, entry.name);
        return entry.isDirectory() ? filesBelow(path) : [path];
      }),
    )
  ).flat();
}

function cssContentText(css) {
  return [...css.matchAll(/\bcontent\s*:\s*(['"])(.*?)\1/gsu)]
    .map((match) =>
      match[2]
        .replace(/\\([\da-f]{1,6})\s?/giu, (_, value) =>
          String.fromCodePoint(Number.parseInt(value, 16)),
        )
        .replace(/\\(['"\\])/gu, '$1'),
    )
    .join('');
}

function textFromCodePoints(codePoints) {
  return [...codePoints]
    .sort((left, right) => left - right)
    .map((codePoint) => String.fromCodePoint(codePoint))
    .join('');
}

function unicodeRange(codePoints) {
  const sorted = [...codePoints].sort((left, right) => left - right);
  const ranges = [];
  let start = sorted[0];
  let end = start;
  for (const codePoint of sorted.slice(1)) {
    if (codePoint === end + 1) {
      end = codePoint;
      continue;
    }
    ranges.push([start, end]);
    start = codePoint;
    end = codePoint;
  }
  if (start !== undefined) ranges.push([start, end]);
  return ranges
    .map(([rangeStart, rangeEnd]) =>
      rangeStart === rangeEnd
        ? `U+${rangeStart.toString(16).toUpperCase()}`
        : `U+${rangeStart.toString(16).toUpperCase()}-${rangeEnd
            .toString(16)
            .toUpperCase()}`,
    )
    .join(', ');
}

const files = await filesBelow(distDirectory);
const pages = await Promise.all(
  files
    .filter((file) => extname(file) === '.html')
    .map(async (file) => ({
      file,
      text: weightedText(await readFile(file, 'utf8')),
    })),
);
const cssText = (
  await Promise.all(
    files
      .filter((file) => extname(file) === '.css')
      .map(async (file) => cssContentText(await readFile(file, 'utf8'))),
  )
).join('');

const sourceFont = await readFile(sourceFontPath);
await mkdir(generatedDirectory, { recursive: true });
const cssBlocks = [
  '/* Generated by scripts/subset-fonts.mjs. Do not edit by hand. */',
];
const pageCssBlocks = new Map();
const summary = [];

for (const weight of FONT_WEIGHTS) {
  const homeText = pages
    .filter(({ file }) => file === homeHtml)
    .map(({ text }) => text[weight])
    .join('');
  const extraText = weight === 400 ? cssText : '';

  const core = withCoreBaseline(codePointsFrom(homeText + extraText));
  const ext = partitionExt(
    new Map(
      pages.map(({ file, text }) => [
        pageKeyFromPath(relative(distDirectory, file)),
        codePointsFrom(text[weight]),
      ]),
    ),
    core,
  );

  for (const [name, codePoints] of [
    ['core', core],
    ...[...ext].map(([group, groupCodePoints]) => [
      `ext-${group}`,
      groupCodePoints,
    ]),
  ]) {
    if (codePoints.size === 0) continue;
    const subset = await subsetFont(
      sourceFont,
      textFromCodePoints(codePoints),
      {
        targetFormat: 'woff2',
        variationAxes: { wght: weight },
        keepFeatures: LAYOUT_FEATURES,
      },
    );
    const hash = createHash('sha256').update(subset).digest('hex').slice(0, 12);
    const filename = `noto-sans-tc-${weight}-${name}.${hash}.woff2`;
    await writeFile(join(generatedDirectory, filename), subset);
    const cssBlock = `@font-face {
  font-family: 'Noto Sans TC';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('/_fonts/${filename}') format('woff2');
  unicode-range: ${unicodeRange(codePoints)};
}`;
    if (name === 'core') cssBlocks.push(cssBlock);
    else {
      const page = name.slice('ext-'.length);
      pageCssBlocks.set(page, [...(pageCssBlocks.get(page) ?? []), cssBlock]);
    }
    summary.push(
      `${weight}-${name}: ${codePoints.size} glyphs, ${Math.round(subset.byteLength / 1024)} KB`,
    );
  }
}

const pageCss = Object.fromEntries(
  [...pageCssBlocks].map(([page, blocks]) => [page, blocks.join('\n\n')]),
);

// Coverage of the final rendered output is verified by scripts/check-font-coverage.mjs.
await writeFile(
  generatedPageCss,
  `${JSON.stringify(pageCss, null, 2)}\n`,
  'utf8',
);
await writeFile(generatedCss, `${cssBlocks.join('\n\n')}\n`, 'utf8');
process.stdout.write(`Noto Sans TC subsets: ${summary.join('; ')}.\n`);
