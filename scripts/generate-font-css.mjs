import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
import process from 'node:process';

const root = process.cwd();
const sourceDirectory = join(root, 'src');
const fontSource = join(
  root,
  'node_modules',
  '@fontsource',
  'noto-sans-tc',
  '400.css',
);
const output = join(root, 'src', 'styles', 'noto-sans-tc.generated.css');
const contentExtensions = new Set(['.astro', '.ts', '.yaml', '.yml']);

async function filesBelow(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const path = join(directory, entry.name);
        return entry.isDirectory() ? filesBelow(path) : [path];
      }),
    )
  ).flat();
}

function rangeContains(range, codePoint) {
  const [start, end = start] = range
    .replace(/^U\+/i, '')
    .split('-')
    .map((value) => Number.parseInt(value, 16));
  return codePoint >= start && codePoint <= end;
}

const sourceFiles = (await filesBelow(sourceDirectory)).filter((file) =>
  contentExtensions.has(extname(file)),
);
const sourceText = (
  await Promise.all(sourceFiles.map((file) => readFile(file, 'utf8')))
).join('\n');
const codePoints = new Set(
  [...sourceText].map((character) => character.codePointAt(0)),
);

const fontCss = await readFile(fontSource, 'utf8');
const blocks = fontCss.match(/\/\*[^*]+\*\/\s*@font-face\s*\{[^}]+\}/g) ?? [];
const selected = blocks.filter((block) => {
  const unicodeRange = block.match(/unicode-range:\s*([^;]+);/)?.[1];
  if (!unicodeRange) return false;
  const ranges = unicodeRange.split(',').map((range) => range.trim());
  return [...codePoints].some((codePoint) =>
    ranges.some((range) => rangeContains(range, codePoint)),
  );
});

const css = `${[
  '/* Generated by scripts/generate-font-css.mjs. Do not edit by hand. */',
  ...selected.map((block) =>
    block
      .replaceAll('url(./files/', "url('@fontsource/noto-sans-tc/files/")
      .replaceAll('.woff2) format', ".woff2') format")
      .replaceAll('.woff) format', ".woff') format"),
  ),
].join('\n\n')}\n`;

await writeFile(output, css, 'utf8');
process.stdout.write(
  `Generated ${selected.length} Noto Sans TC unicode slices.\n`,
);
